export function getLocaleFromCookie(cookieHeader?: string): Locale {
  const match = cookieHeader?.match(/(?:^|;\s*)locale=(en|de)/);
  return match?.[1] === "de" ? "de" : "en";
}

export function t(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  let template = STRINGS[locale][key] ?? STRINGS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      template = template.replaceAll(`{${k}}`, String(v));
    }
  }
  return template;
}
